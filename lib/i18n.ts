/**
 * dirForLanguage (Section 14, I-3) — the single source of truth
 * for the HTML dir of a UI language: 'rtl' for Arabic, 'ltr' for
 * every other supported language. Backed by lib/region.ts
 * isRtlLanguage so the rtl set is defined in exactly one place.
 * The root layout derives the first-paint dir from the saved
 * sb-language cookie and the RegionProvider flips dir live on
 * language change; both should use this mapping.
 */
export function dirForLanguage(language: Language): 'rtl' | 'ltr' {
  return isRtlLanguage(language) ? 'rtl' : 'ltr';
}

export function tFor(language: Language, key: DictKey): string {
  return DICTIONARIES[language][key] ?? DICTIONARIES.en[key];
}

/** Fill {country} / {currency} placeholders in a banner string. */
export function bannerText(
  _language: Language,
  countryName: string,
  currency: string
): string {
  // Section 16: the bannerDetected dictionary key was deleted as a
  // dead key (it was rendered only through this function), so the
  // banner sentence is now an English-only template. That is a real
  // regression for the other 19 languages: the banner shows English
  // regardless of the UI language until a banner key is re-added
  // (which would take the key count from 167 to 168). The
  // placeholders are still filled from the detected region.
  return `You're browsing from ${countryName} — prices shown in ${currency} (≈)`;
}
