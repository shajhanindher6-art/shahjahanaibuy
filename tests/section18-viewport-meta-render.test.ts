// Imported after the mocks so the layout uses the fakes.
import RootLayout, { metadata } from '@/app/layout';

/**
 * What Next 13.5.9 renders from `metadata.viewport`: one
 * `<meta name="viewport">` whose content joins the width and
 * initial-scale fields. This mirrors that derivation (not the
 * layout's JSX — see the header) so the test asserts the tag
 * the browser actually receives.
 */
function renderViewportMeta(viewport: {
  width?: string | number;
  initialScale?: number;
}): string {
  const parts: string[] = [];
  if (viewport.width !== undefined) parts.push(`width=${viewport.width}`);
  if (viewport.initialScale !== undefined) {
    parts.push(`initial-scale=${viewport.initialScale}`);
  }
  return renderToStaticMarkup(
    createElement('meta', { name: 'viewport', content: parts.join(', ') })
  );
}

describe('RootLayout — viewport meta (render test, not source grep)', () => {
  it('the real root layout renders (skip link, theme-color, children)', () => {
    const html = renderToStaticMarkup(
      createElement(RootLayout, null, createElement('main', null, 'hello-test'))
    );
    expect(html).toContain('Skip to content');
    expect(html).toContain('name="theme-color"');
    expect(html).toContain('hello-test');
    expect(html).toContain('lang="en"');
  });

  it('the layout exports viewport metadata: device-width, initial-scale 1', () => {
    expect(metadata.viewport).toEqual({ width: 'device-width', initialScale: 1 });
  });

  it('the viewport tag Next derives from that metadata renders exactly as a mobile browser needs', () => {
    const viewport = metadata.viewport as {
      width?: string | number;
      initialScale?: number;
    };
    const html = renderViewportMeta(viewport);
    expect(html).toBe(
      '<meta name="viewport" content="width=device-width, initial-scale=1"/>'
    );
  });
});
